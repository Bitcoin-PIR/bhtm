#[derive(Clone, Copy)]
enum StreamModeKind {
    Bin,
    Jsonl,
}

fn run_stream_mode(args: &[String], kind: StreamModeKind) {
    let mode_label = match kind {
        StreamModeKind::Bin => "compact binary stripped block deltas",
        StreamModeKind::Jsonl => "stripped block delta JSONL",
    };
    if args.len() < 3 {
        eprintln!("Error: this mode requires <path|->");
        std::process::exit(1);
    }
    let path = &args[2];
    let options = parse_output_options(&args[3..]).unwrap_or_else(|e| {
        eprintln!("Error: {}", e);
        std::process::exit(1);
    });

    eprintln!("=== Block Hash → MuHash Binding ===");
    eprintln!("Mode: {}", mode_label);
    eprintln!();
    eprintln!("Input: {}", path);
    eprintln!();

    let result = if path == "-" {
        match kind {
            StreamModeKind::Bin => stream::process_binary_reader(io::stdin().lock()),
            StreamModeKind::Jsonl => stream::process_jsonl_reader(io::stdin().lock()),
        }
    } else {
        let path = PathBuf::from(path);
        if !path.exists() {
            eprintln!("Error: input file not found: {:?}", path);
            std::process::exit(1);
        }
        match kind {
            StreamModeKind::Bin => stream::process_binary_file(&path),
            StreamModeKind::Jsonl => stream::process_jsonl_file(&path),
        }
    };

    match result {
        Ok(stats) => finish_stats(&stats, &options),
        Err(e) => {
            eprintln!("Error processing stripped block deltas: {}", e);
            std::process::exit(1);
        }
    }
}

/// `bin-teed` is `bin` with SEV-SNP defaults applied — useful when
/// running inside the SEV-SNP UKI where the operator always wants the
/// full attestation triple.
///
/// Defaults applied (if the caller didn't already pass an explicit
/// flag):
/// - `--attestation-out   proof/attestation.bin`
/// - `--report-data-out   proof/report-data.bin`
/// - `--stats-json-out    proof/stats.json`
/// - `--sev-snp-report-out proof/sev-snp-report.bin`
/// - `--sev-missing       fail`
///
/// `--expect-end-core-muhash` is still caller-supplied (it cross-checks
/// the run against Bitcoin Core's `gettxoutsetinfo muhash` value).
fn run_bin_teed_mode(args: &[String]) {
    let passthrough = build_bin_teed_passthrough(args).unwrap_or_else(|e| {
        eprintln!("Error: {}", e);
        std::process::exit(1);
    });
    run_stream_mode(&passthrough, StreamModeKind::Bin)
}

fn run_canonical_job_mode(args: &[String]) {
    if args.len() != 3 {
        eprintln!("Usage: {} canonical-job <job.json>", args[0]);
        std::process::exit(1);
    }
    let loaded = load_job_or_exit(Path::new(&args[2]));
    io::stdout()
        .write_all(&loaded.canonical_json)
        .unwrap_or_else(|e| {
            eprintln!("Error writing canonical job JSON: {}", e);
            std::process::exit(1);
        });
}

fn run_job_env_mode(args: &[String]) {
    if args.len() != 3 {
        eprintln!("Usage: {} job-env <job.json>", args[0]);
        std::process::exit(1);
    }
    let loaded = load_job_or_exit(Path::new(&args[2]));
    print_job_env(&loaded);
}

fn run_job_mode(args: &[String], teed: bool) {
    if args.len() < 4 {
        let mode = if teed { "job-teed" } else { "job" };
        eprintln!("Usage: {} {} <job.json> <path|-> [options]", args[0], mode);
        std::process::exit(1);
    }

    let loaded = load_job_or_exit(Path::new(&args[2]));
    let path = &args[3];
    let mut options = parse_output_options(&args[4..]).unwrap_or_else(|e| {
        eprintln!("Error: {}", e);
        std::process::exit(1);
    });
    apply_job_to_options(&loaded, &mut options).unwrap_or_else(|e| {
        eprintln!("Error: {}", e);
        std::process::exit(1);
    });
    if teed {
        apply_job_teed_defaults(&mut options);
    }

    eprintln!("=== Block Hash → MuHash Binding ===");
    eprintln!(
        "Mode: compact binary stripped block deltas with job.json{}",
        if teed { " + SEV-SNP" } else { "" }
    );
    eprintln!();
    eprintln!("Job:   {}", args[2]);
    eprintln!("Job SHA256: {}", hex::encode(loaded.sha256));
    eprintln!("Input: {}", path);
    eprintln!();

    let result = if path == "-" {
        stream::process_binary_reader(io::stdin().lock())
    } else {
        let path = PathBuf::from(path);
        if !path.exists() {
            eprintln!("Error: input file not found: {:?}", path);
            std::process::exit(1);
        }
        stream::process_binary_file(&path)
    };

    match result {
        Ok(stats) => finish_stats(&stats, &options),
        Err(e) => {
            eprintln!("Error processing stripped block deltas: {}", e);
            std::process::exit(1);
        }
    }
}

fn build_bin_teed_passthrough(args: &[String]) -> Result<Vec<String>, String> {
    if args.len() < 3 {
        return Err("bin-teed mode requires <path|->".into());
    }
    let mut passthrough: Vec<String> = vec![args[0].clone(), String::from("bin"), args[2].clone()];
    let mut has_attestation = false;
    let mut has_report_data = false;
    let mut has_stats = false;
    let mut has_sev = false;
    let mut has_sev_missing = false;
    let mut i = 3;
    while i < args.len() {
        passthrough.push(args[i].clone());
        match args[i].as_str() {
            "--attestation-out" => has_attestation = true,
            "--report-data-out" => has_report_data = true,
            "--stats-json-out" => has_stats = true,
            "--sev-snp-report-out" => has_sev = true,
            "--sev-missing" => has_sev_missing = true,
            _ => {}
        }
        if let Some(val) = args.get(i + 1) {
            if !val.starts_with("--") {
                passthrough.push(val.clone());
                i += 2;
                continue;
            }
        }
        i += 1;
    }
    if !has_attestation {
        passthrough.push("--attestation-out".into());
        passthrough.push("proof/attestation.bin".into());
    }
    if !has_report_data {
        passthrough.push("--report-data-out".into());
        passthrough.push("proof/report-data.bin".into());
    }
    if !has_stats {
        passthrough.push("--stats-json-out".into());
        passthrough.push("proof/stats.json".into());
    }
    if !has_sev {
        passthrough.push("--sev-snp-report-out".into());
        passthrough.push("proof/sev-snp-report.bin".into());
    }
    if !has_sev_missing {
        passthrough.push("--sev-missing".into());
        passthrough.push("fail".into());
    }
    Ok(passthrough)
}

fn apply_job_teed_defaults(options: &mut OutputOptions) {
    if options.attestation_out.is_none() {
        options.attestation_out = Some(PathBuf::from("proof/attestation.bin"));
    }
    if options.report_data_out.is_none() {
        options.report_data_out = Some(PathBuf::from("proof/report-data.bin"));
    }
    if options.stats_json_out.is_none() {
        options.stats_json_out = Some(PathBuf::from("proof/stats.json"));
    }
    if options.sev_snp_report_out.is_none() {
        options.sev_snp_report_out = Some(PathBuf::from("proof/sev-snp-report.bin"));
    }
    if options.job_out.is_none() {
        options.job_out = Some(PathBuf::from("proof/job.json"));
    }
    if options.sev_missing == SevMissingBehaviour::ExitZero {
        options.sev_missing = SevMissingBehaviour::Fail;
    }
}

fn load_job_or_exit(path: &Path) -> LoadedProofJob {
    ProofJob::load(path).unwrap_or_else(|e| {
        eprintln!("Error loading proof job from {}: {}", path.display(), e);
        std::process::exit(1);
    })
}

fn apply_job_to_options(
    loaded: &LoadedProofJob,
    options: &mut OutputOptions,
) -> Result<(), String> {
    let expected_start_height = loaded.job.expected_start_height();
    let expected_start_block_hash = loaded.job.expected_start_block_hash_display();
    let expected_start_muhash = loaded.job.expected_start_muhash();
    let expected_end_core_muhash = loaded.job.expected_end_core_muhash.to_ascii_lowercase();

    require_or_set_u32(
        &mut options.expect_start_height,
        expected_start_height,
        "start height",
    )?;
    require_or_set_string(
        &mut options.expect_start_block_hash,
        expected_start_block_hash,
        "start block hash",
    )?;
    require_or_set_string(
        &mut options.expect_start_muhash,
        expected_start_muhash,
        "start MuHash",
    )?;
    require_or_set_string(
        &mut options.expect_end_core_muhash,
        expected_end_core_muhash,
        "end Core MuHash",
    )?;

    options.job_context = Some(JobContext {
        version: loaded.job.version,
        sha256: loaded.sha256,
        canonical_json: loaded.canonical_json.clone(),
        chain: loaded.job.chain.clone(),
        chunk: loaded.job.chunk.clone(),
        input_url: loaded.job.input_url.clone(),
        input_sha256: loaded.job.input_sha256.clone(),
        upload_url: loaded.job.upload_url.clone(),
    });
    Ok(())
}

fn require_or_set_u32(slot: &mut Option<u32>, expected: u32, label: &str) -> Result<(), String> {
    match slot {
        Some(existing) if *existing != expected => Err(format!(
            "{label} option conflicts with job.json: expected {expected}, got {existing}"
        )),
        Some(_) => Ok(()),
        None => {
            *slot = Some(expected);
            Ok(())
        }
    }
}

fn require_or_set_string(
    slot: &mut Option<String>,
    expected: String,
    label: &str,
) -> Result<(), String> {
    match slot {
        Some(existing) if existing != &expected => Err(format!(
            "{label} option conflicts with job.json: expected {expected}, got {existing}"
        )),
        Some(_) => Ok(()),
        None => {
            *slot = Some(expected);
            Ok(())
        }
    }
}

