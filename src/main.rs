//! Block Hash → MuHash Binding — slim MuHash builder.
//!
//! Main entry point. Reads externally prepared stripped block deltas, verifies
//! each delta against its block header and trusted block hash, applies the
//! supplied MuHash coin deltas, and builds a MuHash Merkle Tree.

use blockhash_to_muhash::job::{LoadedProofJob, ProofJob};
use blockhash_to_muhash::merkle_tree::{
    verify_inclusion_proof, MerkleProofStep, MuHashMerkleTree, SiblingSide,
};
#[cfg(unix)]
use blockhash_to_muhash::sev_snp_guest;
use blockhash_to_muhash::stream;
use blockhash_to_muhash::verify_quote;
use serde_json::{json, Value};
use sha2::{Digest, Sha256};
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone)]
struct JobContext {
    version: u16,
    sha256: [u8; 32],
    canonical_json: Vec<u8>,
    chain: String,
    chunk: String,
    input_url: String,
    input_sha256: String,
    upload_url: String,
}

#[derive(Debug, Default)]
struct OutputOptions {
    attestation_out: Option<PathBuf>,
    report_data_out: Option<PathBuf>,
    stats_json_out: Option<PathBuf>,
    sev_snp_report_out: Option<PathBuf>,
    job_out: Option<PathBuf>,
    job_context: Option<JobContext>,
    expect_start_height: Option<u32>,
    expect_start_block_hash: Option<String>,
    expect_start_muhash: Option<String>,
    expect_end_core_muhash: Option<String>,
    /// Behaviour when `/dev/sev-guest` is missing while writing a
    /// `--sev-snp-report-out`. Defaults to `ExitZero` (matches
    /// `pir-runtime-core/src/attest.rs`); other options are `Fail` and
    /// `Warn`.
    sev_missing: SevMissingBehaviour,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
enum SevMissingBehaviour {
    #[default]
    ExitZero,
    Fail,
    Warn,
}

